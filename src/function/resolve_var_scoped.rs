impl JSFunctionDef {
    /// Resolves variable references within a specific scope
    /// Searches for the variable starting from the given scope and moves upwards
    /// Rewrites bytecode to handle variable access appropriately
    /// Returns the position of the next opcode to process
    /// Handles local, closure, and global variable resolution
    pub fn resolve_scope_var(
        &mut self,
        ctx: &JSContext,
        var_name: JSAtom,
        scope: i32,
        op: u8,
        bc: &mut Vec<u8>, // new generated bytecode
        bc_buf: *mut u8,  // original bytecode
        label: Option<u32>,
        pos_next: usize,
    ) -> usize {
        macro_rules! done {
            ($label:expr) => {
                if let Some(l) = $label {
                    push_vec_u8(bc, opcodes::op_label);
                    push_vec_u32(bc, l);
                    self.label_slots[l as usize].pos2 = bc.len() as i32;
                }
                return pos_next;
            };
        }

        // XXX: could be simpler to use a specific function to
        // resolve the pseudo variables
        let is_pseudo_var = matches!(
            var_name,
            JS_ATOM__home_object_ | JS_ATOM_this_active_func | JS_ATOM_new_target | JS_ATOM_this
        );

        let mut label_done: Option<u32> = None;
        let mut found_var: i32 = -1;

        // resolve local scoped variables: iterate over scoped vars
        let mut at_arg_scope_end = false;
        for item in self.scoped_vars_iter_mut(scope as _) {
            at_arg_scope_end = item.arg_scope_end;

            if item.vd.var_name == var_name {
                if matches!(op, opcodes::op_scope_put_var | opcodes::op_scope_make_ref) {
                    if item.vd.is_const() {
                        push_vec_u8(bc, opcodes::OP_throw_error);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                        push_vec_u8(bc, JS_THROW_VAR_RO);
                        done!(label_done);
                    }
                }
                found_var = item.idx;
                break;
            } else if item.vd.var_name == JS_ATOM__with_ && !is_pseudo_var {
                push_vec_u8(bc, opcodes::OP_get_loc);
                push_vec_u16(bc, item.idx as _);
                label_done.replace(
                    item.fd
                        .var_object_test(ctx, var_name, op, bc, label_done, true),
                );
            }
        }

        // let mut cov = self.scopes[scope as usize].first;
        // while cov >= 0 {
        //     let (cur_var_name, is_const, scope_next) = {
        //         let vd = self.vars.get(cov as usize).unwrap();
        //         (vd.var_name, vd.is_const(), vd.scope_next)
        //     };

        //     if cur_var_name == var_name {
        //         if matches!(op, opcodes::op_scope_put_var | opcodes::op_scope_make_ref) {
        //             if is_const {
        //                 push_vec_u8(bc, opcodes::OP_throw_error);
        //                 push_vec_u32(bc, var_name.dup(ctx.rt()).0);
        //                 push_vec_u8(bc, JS_THROW_VAR_RO);
        //                 done!(label_done);
        //             }
        //         }
        //         found_var = cov;
        //         break;
        //     } else if cur_var_name == JS_ATOM__with_ && !is_pseudo_var {
        //         push_vec_u8(bc, opcodes::OP_get_loc);
        //         push_vec_u16(bc, cov as _);
        //         label_done
        //             .replace(self.var_object_test(ctx, var_name, op, bc, label_done, true));
        //     }

        //     cov = scope_next;
        // }

        // cov == ARG_SCOPE_END

        if found_var < 0 {
            if !at_arg_scope_end {
                // argument scope: variables are not visible but pseudo variables are visible
                found_var = self.find_var(var_name).map_or(-1, |x| x as i32);
            }
            if found_var < 0 && is_pseudo_var {
                found_var = self
                    .resolve_pseudo_var(ctx, var_name)
                    .map_or(-1, |x| x as i32);
            }
            if found_var < 0 && var_name == JS_ATOM_arguments && self.has_arguments_binding {
                // 'arguments' pseudo variable
                found_var = self.add_arguments(ctx, false).map_or(-1, |x| x as i32);
            }
            if found_var < 0 && self.is_func_expr && var_name == self.func_name {
                // add a new variable with the function name
                found_var = unsafe { self.add_func_var(ctx, var_name).map_or(-1, |x| x as i32) }
            }
        }

        if found_var >= 0 {
            // var or arg found
            return self.resolve_scope_var_vardef(
                ctx, var_name, op, bc, bc_buf, label, label_done, pos_next, found_var,
            );
        }

        if !is_pseudo_var {
            if !at_arg_scope_end && self.var_object_idx.is_some() {
                // check eval object:
                // test `var_name` defined on `<val>` object
                push_vec_u8(bc, opcodes::OP_get_loc);
                push_vec_u16(bc, self.var_object_idx.unwrap());
                label_done.replace(self.var_object_test(ctx, var_name, op, bc, label_done, false));
            }

            if let Some(av) = self.arg_var_object_idx {
                // check eval object in argument scope:
                // test `var_name` defined on `<arg_val>` object
                push_vec_u8(bc, opcodes::OP_get_loc);
                push_vec_u16(bc, av);
                label_done.replace(self.var_object_test(ctx, var_name, op, bc, label_done, false));
            }
        }

        debug_assert_eq!(found_var, -1);

        // check parent scopes: walk scopes upward till root
        let mut fd: *mut JSFunctionDef = self;

        'walk_scopes: while unsafe { !(*fd).parent.is_null() } {
            let scope_level = unsafe { (*fd).parent_scope_level };
            debug_assert!(scope_level >= 0);

            fd = unsafe { (*fd).parent };

            let mut is_arg_scope = false;

            // iterate over scoped vars
            for item in unsafe { (*fd).scoped_vars_iter_mut(scope_level as _) } {
                is_arg_scope = item.arg_scope_end;

                if item.vd.var_name == var_name {
                    if matches!(
                        op as u8,
                        opcodes::op_scope_put_var | opcodes::op_scope_make_ref
                    ) {
                        if item.vd.is_const() {
                            push_vec_u8(bc, opcodes::OP_throw_error);
                            push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                            push_vec_u8(bc, JS_THROW_VAR_RO);
                            done!(label_done);
                        }
                    }

                    found_var = item.idx;
                    break 'walk_scopes;
                }

                if item.vd.var_name == JS_ATOM__with_ && !is_pseudo_var {
                    item.vd.set_is_captured(true);
                    match item.fd.get_closure_var2(
                        ctx,
                        fd,
                        true,
                        false,
                        item.idx as u16,
                        item.vd.var_name,
                        false,
                        false,
                        JSVarKindEnum::JS_VAR_NORMAL,
                    ) {
                        Ok(vi) => {
                            push_vec_u8(bc, opcodes::OP_get_var_ref);
                            push_vec_u16(bc, vi);
                            label_done.replace(
                                self.var_object_test(ctx, var_name, op, bc, label_done, true),
                            );
                        }
                        Err(_) => {
                            todo!()
                        }
                    }
                }
            }

            // let mut cov = unsafe { (*fd).scopes[scope_level as usize].first };
            // while cov >= 0 {
            //     let vd = unsafe { (*fd).vars.get_mut(cov as usize).unwrap() };
            //     if vd.var_name == var_name {
            //         if matches!(
            //             op as u8,
            //             opcodes::op_scope_put_var | opcodes::op_scope_make_ref
            //         ) {
            //             if vd.is_const() {
            //                 push_vec_u8(bc, opcodes::OP_throw_error);
            //                 push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            //                 push_vec_u8(bc, JS_THROW_VAR_RO);
            //                 done!(label_done);
            //             }
            //         }

            //         found_var = cov;
            //         break 'walk_scopes;
            //     }

            //     if vd.var_name == JS_ATOM__with_ && !is_pseudo_var {
            //         vd.set_is_captured(true);
            //         match self.get_closure_var2(
            //             ctx,
            //             fd,
            //             true,
            //             false,
            //             cov as u16,
            //             vd.var_name,
            //             false,
            //             false,
            //             JSVarKindEnum::JS_VAR_NORMAL,
            //         ) {
            //             Ok(vi) => {
            //                 push_vec_u8(bc, opcodes::OP_get_var_ref);
            //                 push_vec_u16(bc, vi);
            //                 label_done.replace(
            //                     self.var_object_test(ctx, var_name, op, bc, label_done, true),
            //                 );
            //             }
            //             Err(_) => {
            //                 todo!()
            //             }
            //         }
            //     }

            //     cov = vd.scope_next;
            // }
            // let is_arg_scope = cov == ARG_SCOPE_END;

            debug_assert_eq!(found_var, -1);

            if !is_arg_scope {
                found_var = unsafe { (*fd).find_var(var_name).map_or(-1, |x| x as i32) };
                if found_var >= 0 {
                    break;
                }
            }
            if is_pseudo_var {
                if let Some(i) = unsafe { (*fd).resolve_pseudo_var(ctx, var_name) } {
                    found_var = i as i32;
                    break;
                }
            }
            if var_name == JS_ATOM_arguments && unsafe { (*fd).has_arguments_binding } {
                if let Ok(i) = unsafe { (*fd).add_arguments(ctx, false) } {
                    found_var = i as i32;
                }
                break;
            }

            unsafe {
                if (*fd).is_func_expr && (*fd).func_name == var_name {
                    // add a new variable with the function name
                    if let Ok(i) = (*fd).add_func_var(ctx, var_name) {
                        found_var = i as i32;
                    }
                    break;
                }
            }

            // check eval object
            unsafe {
                if !is_arg_scope && (*fd).var_object_idx.is_some() && !is_pseudo_var {
                    let vd = (*fd)
                        .vars
                        .get_mut((*fd).var_object_idx.unwrap() as usize)
                        .unwrap();
                    vd.set_is_captured(true);
                    let cv_id = self
                        .get_closure_var2(
                            ctx,
                            fd,
                            true,
                            false,
                            (*fd).var_object_idx.unwrap(),
                            vd.var_name,
                            false,
                            false,
                            JSVarKindEnum::JS_VAR_NORMAL,
                        )
                        .unwrap();

                    push_vec_u8(bc, opcodes::OP_get_var_ref);
                    push_vec_u16(bc, cv_id);
                    label_done
                        .replace(self.var_object_test(ctx, var_name, op, bc, label_done, false));
                }
            }

            // check eval object in argument scope
            unsafe {
                if !is_pseudo_var && (*fd).arg_var_object_idx.is_some() {
                    let vd = (*fd)
                        .vars
                        .get_mut((*fd).arg_var_object_idx.unwrap() as usize)
                        .unwrap();
                    vd.set_is_captured(true);
                    let cv_id = self
                        .get_closure_var2(
                            ctx,
                            fd,
                            true,
                            false,
                            (*fd).arg_var_object_idx.unwrap(),
                            vd.var_name,
                            false,
                            false,
                            JSVarKindEnum::JS_VAR_NORMAL,
                        )
                        .unwrap();

                    push_vec_u8(bc, opcodes::OP_get_var_ref);
                    push_vec_u16(bc, cv_id);
                    label_done
                        .replace(self.var_object_test(ctx, var_name, op, bc, label_done, false));
                }
            }

            if unsafe { (*fd).is_eval } {
                break; // it is necessarily the top level function
            }
        } // while: walk scope upward

        // check direct eval scope
        // (in the closure of the eval function which is necessarily at the top level)
        if fd.is_null() {
            fd = self;
        }

        // find closure variable
        let mut found_closure: Option<u16> = None;

        if found_var < 0 && unsafe { (*fd).is_eval } {
            if let Some(cvars) = unsafe { (*fd).closure_vars.as_ref() } {
                for (i, cv) in cvars.iter().enumerate() {
                    if var_name == cv.var_name {
                        found_closure.replace(if fd != self {
                            self.get_closure_var2(
                                ctx,
                                fd,
                                false,
                                cv.is_arg(),
                                i as _,
                                cv.var_name,
                                cv.is_const(),
                                cv.is_lexical(),
                                cv.var_kind(),
                            )
                            .unwrap() // can't fail
                        } else {
                            i as u16
                        });
                        break;
                    } else if !is_pseudo_var
                        && matches!(
                            cv.var_name,
                            JS_ATOM__var_ | JS_ATOM__arg_var_ | JS_ATOM__with_
                        )
                    {
                        let cv_id = if fd != self {
                            self.get_closure_var2(
                                ctx,
                                fd,
                                false,
                                cv.is_arg(),
                                i as _,
                                cv.var_name,
                                false,
                                false,
                                JSVarKindEnum::JS_VAR_NORMAL,
                            )
                            .unwrap()
                        } else {
                            i as u16
                        };

                        push_vec_u8(bc, opcodes::OP_get_var_ref);
                        push_vec_u16(bc, cv_id);
                        label_done.replace(self.var_object_test(
                            ctx,
                            var_name,
                            op,
                            bc,
                            label_done,
                            cv.var_name == JS_ATOM__with_,
                        ));
                    }
                }
            }
        }

        if found_var >= 0 && found_closure.is_none() {
            // find the corresponding closure variable
            found_closure = if found_var & ARGUMENT_VAR_OFFSET != 0 {
                unsafe {
                    (*fd).args[(found_var - ARGUMENT_VAR_OFFSET) as usize].set_is_captured(true);
                }
                self.get_closure_var(
                    ctx,
                    fd,
                    true,
                    (found_var - ARGUMENT_VAR_OFFSET) as u16,
                    var_name,
                    false,
                    false,
                    JSVarKindEnum::JS_VAR_NORMAL,
                )
            } else {
                let (is_const, is_lexical, var_kind) = {
                    let vd = unsafe { (*fd).vars.get_mut(found_var as usize).unwrap() };
                    vd.set_is_captured(true);
                    (vd.is_const(), vd.is_lexical(), vd.var_kind())
                };

                self.get_closure_var(
                    ctx,
                    fd,
                    false,
                    found_var as u16,
                    var_name,
                    is_const,
                    is_lexical,
                    var_kind,
                )
            }
            .ok();
        }

        if let Some(cv) = found_closure {
            // access closure
            self.resolve_scope_var_closure(
                ctx, var_name, op, bc, bc_buf, label, label_done, pos_next, cv,
            )
        } else {
            // access global
            self.resolve_scope_var_global(
                ctx, var_name, op, bc, bc_buf, label, label_done, pos_next,
            )
        }
    }

    /// acccess found vardef: for a var or arg
    fn resolve_scope_var_vardef(
        &mut self,
        ctx: &JSContext,
        var_name: JSAtom,
        op: u8,
        bc: &mut Vec<u8>,
        bc_buf: *mut u8,
        label: Option<u32>,
        label_done: Option<u32>,
        mut pos_next: usize,
        mut var_id: i32,
    ) -> usize {
        if var_id & ARGUMENT_VAR_OFFSET == 0
            && matches!(
                op as u8,
                opcodes::op_scope_put_var | opcodes::op_scope_make_ref
            )
            && self.vars[var_id as usize].is_const()
        {
            // in case assigning a function expression name in strict mode.
            // this is not allowed.
            push_vec_u8(bc, opcodes::OP_throw_error);
            push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            push_vec_u8(bc, JS_THROW_VAR_RO);
        } else {
            // op_scope_put_var_init is only used to initialize a
            // lexical variable, so it is never used in a with or var object. It
            // can be used with a closure (module global variable case).
            match op as u8 {
                opcodes::op_scope_make_ref => {
                    let label = label
                        .and_then(|l| self.label_slots.get(l as usize))
                        .unwrap();

                    if var_id & ARGUMENT_VAR_OFFSET == 0
                        && self.vars[var_id as usize].var_kind()
                            == JSVarKindEnum::JS_VAR_FUNCTION_NAME
                    {
                        // Create a dummy object reference for the func_var
                        push_vec_u8(bc, opcodes::OP_object);
                        push_vec_u8(bc, opcodes::OP_get_loc);
                        push_vec_u16(bc, var_id as u16);
                        push_vec_u8(bc, opcodes::OP_define_field);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                        push_vec_u8(bc, opcodes::OP_push_atom_value);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                    } else if label_done.is_none() && can_optimize_put_ref_value(bc_buf, label.pos)
                    {
                        let get_op = if var_id & ARGUMENT_VAR_OFFSET != 0 {
                            var_id -= ARGUMENT_VAR_OFFSET;
                            OpCode::GET_ARG
                        } else {
                            if self.vars.get(var_id as usize).unwrap().is_lexical() {
                                OpCode::GET_LOC_CHECK
                            } else {
                                OpCode::GET_LOC
                            }
                        };
                        pos_next =
                            optimize_scope_make_ref(bc, bc_buf, label, pos_next, get_op, var_id);
                    } else {
                        // Create a dummy object with a named slot that is
                        // a reference to the local variable
                        if var_id & ARGUMENT_VAR_OFFSET != 0 {
                            push_vec_u8(bc, opcodes::OP_make_arg_ref);
                            push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                            push_vec_u16(bc, (var_id - ARGUMENT_VAR_OFFSET) as _);
                        } else {
                            push_vec_u8(bc, opcodes::OP_make_loc_ref);
                            push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                            push_vec_u16(bc, var_id as u16);
                        }
                    }
                }
                opcodes::op_scope_get_ref
                | opcodes::op_scope_get_var_checkthis
                | opcodes::op_scope_get_var_undef
                | opcodes::op_scope_get_var
                | opcodes::op_scope_put_var
                | opcodes::op_scope_put_var_init => {
                    debug_assert!(label.is_none());

                    let is_put = matches!(
                        op as u8,
                        opcodes::op_scope_put_var | opcodes::op_scope_put_var_init
                    );

                    if op == opcodes::op_scope_get_ref {
                        push_vec_u8(bc, opcodes::OP_undefined);
                    }
                    if var_id & ARGUMENT_VAR_OFFSET != 0 {
                        push_vec_u8(
                            bc,
                            if is_put {
                                OpCode::PUT_ARG
                            } else {
                                OpCode::GET_ARG
                            } as u8,
                        );
                        push_vec_u16(bc, (var_id - ARGUMENT_VAR_OFFSET) as u16);
                    } else {
                        let is_lexical = self.vars[var_id as usize].is_lexical();
                        if is_put {
                            // scope_put_XXX
                            if is_lexical {
                                if op == opcodes::op_scope_put_var_init {
                                    push_vec_u8(
                                        bc,
                                        if var_name == JS_ATOM_this {
                                            // 'this' can only be initialized once
                                            OpCode::PUT_LOC_CHECK_INIT
                                        } else {
                                            OpCode::PUT_LOC
                                        } as u8,
                                    );
                                } else {
                                    push_vec_u8(bc, OpCode::PUT_LOC_CHECK as u8);
                                }
                            } else {
                                push_vec_u8(bc, OpCode::PUT_LOC as u8);
                            }
                        } else {
                            // scope_get_XXX
                            if is_lexical {
                                push_vec_u8(
                                    bc,
                                    if op == opcodes::op_scope_get_var_checkthis {
                                        // only used for 'this' return in derived class constructors
                                        OpCode::GET_LOC_CHECKTHIS
                                    } else {
                                        OpCode::GET_LOC_CHECK
                                    } as u8,
                                );
                            } else {
                                push_vec_u8(bc, OpCode::GET_LOC as u8);
                            }
                        }
                        push_vec_u16(bc, var_id as _);
                    }
                }
                opcodes::op_scope_delete_var => {
                    push_vec_u8(bc, opcodes::OP_push_false);
                }
                _ => {}
            }
        }

        if let Some(l) = label_done {
            push_vec_u8(bc, opcodes::op_label);
            push_vec_u32(bc, l);
            self.label_slots[l as usize].pos2 = bc.len() as i32;
        }
        pos_next
    }

    /// Handles resolution of closure variables
    /// Processes variable access operations for closure variables
    /// Handles special cases for function names and lexical variables
    /// Generates appropriate bytecode for closure variable access
    fn resolve_scope_var_closure(
        &mut self,
        ctx: &JSContext,
        var_name: JSAtom,
        op: u8,
        bc: &mut Vec<u8>,
        bc_buf: *mut u8,
        label: Option<u32>,
        label_done: Option<u32>,
        mut pos_next: usize,
        idx: u16,
    ) -> usize {
        let cv = self
            .closure_vars
            .as_ref()
            .and_then(|a| a.get(idx as usize))
            .unwrap();

        if cv.is_const()
            && matches!(
                op as u8,
                opcodes::op_scope_put_var | opcodes::op_scope_make_ref
            )
        {
            push_vec_u8(bc, opcodes::OP_throw_error);
            push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            push_vec_u8(bc, JS_THROW_VAR_RO);
        } else {
            match op as u8 {
                opcodes::op_scope_make_ref => {
                    let label = label
                        .and_then(|l| self.label_slots.get(l as usize))
                        .unwrap();

                    if cv.var_kind() == JSVarKindEnum::JS_VAR_FUNCTION_NAME {
                        // Create a dummy object reference for the func_var
                        push_vec_u8(bc, opcodes::OP_object);
                        push_vec_u8(bc, opcodes::OP_get_var_ref);
                        push_vec_u16(bc, idx as _);
                        push_vec_u8(bc, opcodes::OP_define_field);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                        push_vec_u8(bc, opcodes::OP_push_atom_value);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                    } else if label_done.is_none() && can_optimize_put_ref_value(bc_buf, label.pos)
                    {
                        pos_next = optimize_scope_make_ref(
                            bc,
                            bc_buf,
                            label,
                            pos_next,
                            if cv.is_lexical() {
                                OpCode::GET_VAR_REF_CHECK
                            } else {
                                OpCode::GET_VAR_REF
                            },
                            idx as _,
                        );
                    } else {
                        // Create a dummy object with a named slot that is
                        // a reference to the closure variable
                        push_vec_u8(bc, opcodes::OP_make_var_ref_ref);
                        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                        push_vec_u16(bc, idx as _);
                    }
                }
                opcodes::op_scope_get_ref
                | opcodes::op_scope_get_var_undef
                | opcodes::op_scope_get_var
                | opcodes::op_scope_put_var
                | opcodes::op_scope_put_var_init => {
                    let is_put = matches!(
                        op as u8,
                        opcodes::op_scope_put_var | opcodes::op_scope_put_var_init
                    );

                    if op == opcodes::op_scope_get_ref {
                        // XXX: should create a dummy object with a named slot that is
                        // a reference to the closure variable
                        push_vec_u8(bc, opcodes::OP_undefined);
                    }

                    if is_put {
                        if cv.is_lexical() {
                            if op == opcodes::op_scope_put_var_init {
                                // 'this' can only be initialized once
                                if var_name == JS_ATOM_this {
                                    push_vec_u8(bc, opcodes::OP_put_var_ref_check_init);
                                } else {
                                    push_vec_u8(bc, opcodes::OP_put_var_ref);
                                }
                            } else {
                                push_vec_u8(bc, opcodes::OP_put_var_ref_check);
                            }
                        } else {
                            push_vec_u8(bc, opcodes::OP_put_var_ref);
                        }
                    } else {
                        push_vec_u8(
                            bc,
                            if cv.is_lexical() {
                                opcodes::OP_get_var_ref_check
                            } else {
                                opcodes::OP_get_var_ref
                            },
                        );
                    }
                    push_vec_u16(bc, idx as _);
                }
                opcodes::op_scope_delete_var => {
                    push_vec_u8(bc, opcodes::OP_push_false);
                }
                _ => {}
            } // match op
        }

        if let Some(l) = label_done {
            push_vec_u8(bc, opcodes::op_label);
            push_vec_u32(bc, l);
            self.label_slots[l as usize].pos2 = bc.len() as i32;
        }
        pos_next
    }

    /// Handles resolution of global variables
    /// Processes variable access operations for global variables
    /// Generates appropriate bytecode for global variable access
    /// Handles special cases for variable initialization and deletion
    fn resolve_scope_var_global(
        &mut self,
        ctx: &JSContext,
        var_name: JSAtom,
        op: u8,
        bc: &mut Vec<u8>,
        bc_buf: *mut u8, // JSFunctionDef::byte_code buffer ptr
        label: Option<u32>,
        label_done: Option<u32>,
        mut pos_next: usize,
    ) -> usize {
        match op as u8 {
            opcodes::op_scope_make_ref => {
                let label = label
                    .and_then(|l| self.label_slots.get_mut(l as usize))
                    .unwrap();

                if label_done.is_none() && can_optimize_put_global_ref_value(bc_buf, label.pos) {
                    pos_next = optimize_scope_make_global_ref(
                        ctx,
                        self.js_mode,
                        bc,
                        bc_buf,
                        label,
                        pos_next as _,
                        var_name,
                    ) as _;
                } else {
                    push_vec_u8(bc, opcodes::OP_make_var_ref);
                    push_vec_u32(bc, var_name.dup(ctx.rt()).0);
                }
            }
            opcodes::op_scope_get_ref => {
                // XXX: should create a dummy object with a named slot that is
                // a reference to the global variable
                push_vec_u8(bc, opcodes::OP_undefined);
                push_vec_u8(bc, opcodes::OP_get_var);
                push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            }
            opcodes::op_scope_get_var_undef
            | opcodes::op_scope_get_var
            | opcodes::op_scope_put_var => {
                push_vec_u8(
                    bc,
                    opcodes::OP_get_var_undef + (op as u8 - opcodes::op_scope_get_var_undef),
                );
                push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            }
            opcodes::op_scope_put_var_init => {
                push_vec_u8(bc, opcodes::OP_put_var_init);
                push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            }
            opcodes::op_scope_delete_var => {
                push_vec_u8(bc, opcodes::OP_delete_var);
                push_vec_u32(bc, var_name.dup(ctx.rt()).0);
            }
            _ => {}
        }

        if let Some(l) = label_done {
            push_vec_u8(bc, opcodes::op_label);
            push_vec_u32(bc, l);
            self.label_slots[l as usize].pos2 = bc.len() as i32;
        }
        pos_next
    }

    /// Resolves special pseudo variables (this, new.target, etc.)
    /// Returns the variable definition index if found.
    /// Returns None if the variable is not a pseudo variable
    fn resolve_pseudo_var(&mut self, ctx: &JSContext, var_name: JSAtom) -> Option<u16> {
        if !self.has_this_binding {
            return None;
        }

        match var_name {
            JS_ATOM__home_object_ => {
                // 'home_object' pseudo variable
                if self.home_object_var_idx.is_none() {
                    self.home_object_var_idx = Some(self.add_var(ctx, var_name).expect("TODO"));
                }
                self.home_object_var_idx
            }
            JS_ATOM_this_active_func => {
                // 'this.active_func' pseudo variable
                if self.this_active_func_var_idx.is_none() {
                    self.this_active_func_var_idx =
                        Some(self.add_var(ctx, var_name).expect("TODO"));
                }
                self.this_active_func_var_idx
            }
            JS_ATOM_new_target => {
                // 'new.target' pseudo variable
                if self.new_target_var_idx.is_none() {
                    self.new_target_var_idx = Some(self.add_var(ctx, var_name).expect("TODO"));
                }
                self.new_target_var_idx
            }
            JS_ATOM_this => {
                // 'this' pseudo variable
                if self.this_var_idx.is_none() {
                    self.this_var_idx = Some(self.add_var_this(ctx).unwrap());
                }
                self.this_var_idx
            }
            _ => None,
        }
    }

    /// test if 'var_name' is in the variable object on the stack. If is it
    /// the case, handle it and jump to 'label_done'.
    /// If argument `label_done` is None, new label will be created.
    /// Returns the original label_done or new created label for label_done
    fn var_object_test(
        &mut self,
        ctx: &JSContext,
        var_name: JSAtom,
        op: u8,
        bc: &mut Vec<u8>,
        label_done: Option<u32>,
        is_with: bool,
    ) -> u32 {
        let label: u32 = label_done.unwrap_or_else(|| self.add_label().expect("TODO"));

        push_vec_u8(
            bc,
            if op == opcodes::op_scope_get_var_undef {
                opcodes::OP_with_get_var as u8
            } else {
                opcodes::OP_with_get_var + (op as u8 - opcodes::op_scope_get_var)
            },
        );
        push_vec_u32(bc, var_name.dup(ctx.rt()).0);
        push_vec_u32(bc, label);
        push_vec_u8(bc, is_with as u8);

        self.update_label_ref_count(label as _, 1);

        #[cfg(feature = "short_opcode")]
        {
            self.jump_slots_cap += 1;
        }

        label
    }
}

/// Resolves special pseudo variables (this, new.target, etc.)
/// Returns the variable definition index if found
/// Returns None if the variable is not a pseudo variable
#[deprecated(note = "use JSFunctionDef::resolve_pseudo_var() instead")]
pub unsafe fn resolve_pseudo_var(
    ctx: &JSContext,
    s: *mut JSFunctionDef,
    var_name: JSAtom,
) -> Option<u16> {
    (*s).resolve_pseudo_var(ctx, var_name)
}

