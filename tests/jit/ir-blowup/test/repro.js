// `repro` is ONE straight-line basic block holding 500 calls. Each call used to
// earn its own post-call OSR entry, and an entry is not free: `block_range`
// hands it the whole tail of its block and `block_for` gives that tail a
// Cranelift block of its own, so every copy stays in the compiled code. The cost
// was therefore O(calls x block length), which is enough to push the function
// past Cranelift's `CodeTooLarge`.
//
// The shape is ordinary -- a long straight-line run of calls -- and it is what
// test262's `built-ins/Map/valid-keys.js` does by accident: 116 `call_method`s in
// a 658-instruction block, 2781 bytecodes in, 10.5M IR instructions out, 31 s per
// compile attempt, and a function that never got native code at all.
//
// Measured on this file (release, i7-13700K, `--jit`):
//   before the OSR budget:  41 s, compile_failures=4, compiled 5 of 6
//   after  the OSR budget:   1 s, compile_failures=0, compiled 6 of 6
